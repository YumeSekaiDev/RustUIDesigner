//! Project folder bootstrap: detect Rust sources, create Cargo layout, sync files.

use crate::codegen;
use crate::model::FormDocument;
use std::fs;
use std::path::{Path, PathBuf};

pub const FORM_FILE_NAME: &str = "form.json";

pub fn has_rust_sources(folder: &Path) -> bool {
    folder.join("src/main.rs").is_file() || folder.join("src/app.rs").is_file()
}

pub fn form_json_path(folder: &Path) -> PathBuf {
    folder.join(FORM_FILE_NAME)
}

pub fn package_name_from_folder(folder: &Path) -> String {
    let raw = folder
        .file_name()
        .and_then(|s| s.to_str())
        .unwrap_or("designed_app");
    let mut name = String::new();
    for c in raw.chars() {
        if c.is_ascii_alphanumeric() {
            name.push(c.to_ascii_lowercase());
        } else if c == '-' || c == '_' {
            name.push('_');
        }
    }
    if name.is_empty() || name.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("app_{name}")
    } else {
        name
    }
}

/// Create or refresh a project in `folder`.
///
/// - `Cargo.toml` is written **only if missing** (with eframe/egui deps), then left alone.
/// - `src/main.rs` and `src/app.rs` are always regenerated from the design.
/// - `form.json` is always written.
pub fn create_cargo_project(folder: &Path, doc: &FormDocument) -> Result<Vec<PathBuf>, String> {
    if !folder.is_dir() {
        return Err(format!("Not a directory: {}", folder.display()));
    }

    let src = folder.join("src");
    fs::create_dir_all(&src).map_err(|e| format!("Create src/: {e}"))?;

    let mut paths = Vec::new();

    let cargo_toml_path = folder.join("Cargo.toml");
    if !cargo_toml_path.is_file() {
        let pkg = package_name_from_folder(folder);
        fs::write(&cargo_toml_path, generate_cargo_toml(&pkg))
            .map_err(|e| format!("Write Cargo.toml: {e}"))?;
        paths.push(cargo_toml_path.clone());
    }

    let written = write_generated_sources(folder, doc)?;
    paths.extend(written);

    let form_path = form_json_path(folder);
    let json = doc
        .to_json()
        .map_err(|e| format!("Serialize form.json: {e}"))?;
    fs::write(&form_path, json).map_err(|e| format!("Write form.json: {e}"))?;
    paths.push(form_path);

    // Verify the required project files exist on disk.
    for required in [
        folder.join("Cargo.toml"),
        folder.join("src/main.rs"),
        folder.join("src/app.rs"),
    ] {
        if !required.is_file() {
            return Err(format!(
                "Write reported success but file missing: {}",
                required.display()
            ));
        }
    }

    Ok(paths)
}

/// Write (or overwrite) `src/main.rs` and `src/app.rs` from the current design.
pub fn write_generated_sources(folder: &Path, doc: &FormDocument) -> Result<Vec<PathBuf>, String> {
    let src = folder.join("src");
    fs::create_dir_all(&src).map_err(|e| format!("Create src/: {e}"))?;

    let main_path = src.join("main.rs");
    let app_path = src.join("app.rs");

    fs::write(&main_path, codegen::generate_main_rs(doc))
        .map_err(|e| format!("Write {}: {e}", main_path.display()))?;
    fs::write(&app_path, codegen::generate_app_rs(doc))
        .map_err(|e| format!("Write {}: {e}", app_path.display()))?;

    Ok(vec![main_path, app_path])
}

/// Write only `form.json` (the design) into `folder`. Creates the folder's
/// `form.json` if needed; never touches Cargo.toml or generated sources.
/// This is what autosave uses so work survives closing the app.
pub fn save_form(folder: &Path, doc: &FormDocument) -> Result<PathBuf, String> {
    if !folder.is_dir() {
        return Err(format!("Not a directory: {}", folder.display()));
    }
    let form_path = form_json_path(folder);
    let json = doc
        .to_json()
        .map_err(|e| format!("Serialize form.json: {e}"))?;
    fs::write(&form_path, json).map_err(|e| format!("Write form.json: {e}"))?;
    Ok(form_path)
}

pub fn load_form_if_present(folder: &Path) -> Result<Option<FormDocument>, String> {
    let path = form_json_path(folder);
    if !path.is_file() {
        return Ok(None);
    }
    let text = fs::read_to_string(&path).map_err(|e| format!("Read form.json: {e}"))?;
    let doc = FormDocument::from_json(&text).map_err(|e| format!("Parse form.json: {e}"))?;
    Ok(Some(doc))
}

fn generate_cargo_toml(package_name: &str) -> String {
    format!(
        r#"[package]
name = "{package_name}"
version = "0.1.0"
edition = "2021"
description = "Generated by Form Designer"

[dependencies]
eframe = "0.31.1"
egui = "0.31.1"

# Add more crates here as needed. Form Designer will not overwrite this file
# after it has been created.
"#
    )
}

/// Flat listing of files under the project folder (skips target/ and .git/).
pub fn list_project_files(folder: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    collect_files(folder, folder, &mut files);
    files.sort();
    files
}

fn collect_files(root: &Path, dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        if name == "target" || name == ".git" || name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect_files(root, &path, out);
        } else if path.is_file() {
            out.push(path);
        }
    }
}

pub fn relative_display(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| path.display().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::FormDocument;
    use std::time::{SystemTime, UNIX_EPOCH};

    #[test]
    fn create_cargo_project_writes_three_files() {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("form_designer_proj_{nanos}"));
        fs::create_dir_all(&dir).unwrap();

        let paths = create_cargo_project(&dir, &FormDocument::new_blank()).unwrap();
        assert!(dir.join("Cargo.toml").is_file());
        assert!(dir.join("src/main.rs").is_file());
        assert!(dir.join("src/app.rs").is_file());
        assert!(paths.len() >= 3);

        let cargo = fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(cargo.contains("eframe"));
        assert!(cargo.contains("egui"));
        // Marker so we can detect overwrite.
        fs::write(
            dir.join("Cargo.toml"),
            cargo + "\n# user edit — must survive\n",
        )
        .unwrap();

        let mut doc = FormDocument::new_blank();
        doc.title = "Changed".to_owned();
        doc.width = 800;
        create_cargo_project(&dir, &doc).unwrap();

        let cargo_after = fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(
            cargo_after.contains("user edit — must survive"),
            "Cargo.toml must not be overwritten after creation"
        );
        let main = fs::read_to_string(dir.join("src/main.rs")).unwrap();
        assert!(main.contains("with_title(\"Changed\")"));
        assert!(main.contains("with_inner_size([800.0"));
        let app = fs::read_to_string(dir.join("src/app.rs")).unwrap();
        assert!(app.contains("DesignedApp"));
        assert!(app.contains("fn update("));

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn save_form_roundtrips_without_creating_cargo_project() {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("form_designer_save_{nanos}"));
        fs::create_dir_all(&dir).unwrap();

        let mut doc = FormDocument::new_blank();
        doc.title = "Unsaved Work".to_owned();
        doc.add_control(crate::model::ControlKind::Button, 10.0, 20.0);

        save_form(&dir, &doc).unwrap();
        assert!(dir.join(FORM_FILE_NAME).is_file());
        // Autosave must not bootstrap a whole Cargo project as a side effect.
        assert!(!dir.join("Cargo.toml").exists());
        assert!(!dir.join("src/main.rs").exists());

        let loaded = load_form_if_present(&dir).unwrap().unwrap();
        assert_eq!(loaded.title, "Unsaved Work");
        assert_eq!(loaded.controls.len(), 1);

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn regenerate_workspace_test_project_if_present() {
        let folder = Path::new("/mnt/UNTV News/Game Dev/Rust Basic/test");
        if !folder.is_dir() {
            return;
        }
        let doc = match load_form_if_present(folder).unwrap() {
            Some(doc) => doc,
            None => return,
        };
        write_generated_sources(folder, &doc).unwrap();
        let app = fs::read_to_string(folder.join("src/app.rs")).unwrap();
        assert!(app.contains("fn update("));
        assert!(app.contains("text_box") || app.contains("TextEdit") || app.contains("DesignedApp"));
        let main = fs::read_to_string(folder.join("src/main.rs")).unwrap();
        assert!(main.contains("with_inner_size"));
        assert!(main.contains("with_title"));
    }
}
