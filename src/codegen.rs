//! Code generation: `main.rs` (window bootstrap) and `app.rs` (designed GUI).
//!
//! Generated projects target eframe/egui **0.31** and use `App::update`.

use crate::model::{Control, ControlKind, FormDocument, Orientation, RgbaColor};

/// `main.rs` — window title, size, chrome, and opacity applied to the real viewport.
pub fn generate_main_rs(doc: &FormDocument) -> String {
    let title = escape_rust_string(&doc.title);
    let w = doc.width.max(160) as f32;
    let h = doc.height.max(120) as f32;
    let opacity = doc.opacity.clamp(0.0, 1.0);

    let mut lines = vec![
        "egui::ViewportBuilder::default()".to_owned(),
        format!("            .with_inner_size([{w:.1}, {h:.1}])"),
        format!("            .with_title(\"{title}\")"),
    ];
    if !doc.maximize_box {
        lines.push("            .with_maximize_button(false)".to_owned());
    }
    if !doc.minimize_box {
        lines.push("            .with_minimize_button(false)".to_owned());
    }
    if opacity < 0.999 {
        lines.push("            .with_transparent(true)".to_owned());
    }
    if doc.client_area_only {
        lines.push("            .with_decorations(false)".to_owned());
    }
    // Ensure the last builder call is followed by a comma in NativeOptions.
    let last = lines.len() - 1;
    lines[last].push(',');

    let start_comment = match doc.start_position {
        crate::model::StartPosition::Manual => "            // start_position: Manual",
        crate::model::StartPosition::CenterScreen => "            // start_position: CenterScreen",
        crate::model::StartPosition::CenterParent => "            // start_position: CenterParent",
    };

    format!(
        r#"// Generated by Form Designer — keep in sync with app.rs
// main.rs — applies form title, size, chrome, and opacity to the window.

mod app;

use app::DesignedApp;

fn main() -> eframe::Result<()> {{
    let options = eframe::NativeOptions {{
        viewport: {viewport}
{start_comment}
        ..Default::default()
    }};

    eframe::run_native(
        "{title}",
        options,
        Box::new(|_cc| Ok(Box::new(DesignedApp::default()))),
    )
}}
"#,
        viewport = lines.join("\n"),
    )
}

/// `app.rs` — every control property wired to live widgets inside `App::update`.
pub fn generate_app_rs(doc: &FormDocument) -> String {
    let title = escape_rust_string(&doc.title);
    let opacity = doc.opacity.clamp(0.0, 1.0);
    let back = color_expr_with_opacity(doc.back_color, opacity);
    let clear = clear_color_array(doc.back_color, opacity);

    let mut out = String::new();
    out.push_str("// Generated by Form Designer — keep in sync with main.rs\n");
    out.push_str("// app.rs — designed GUI; all control properties are live.\n\n");
    out.push_str("use eframe::egui;\n\n");

    out.push_str("pub struct DesignedApp {\n");
    out.push_str(
        "    /// Form opacity 0.0–1.0 (also applied via clear_color / panel fill).\n    pub form_opacity: f32,\n",
    );
    for ctrl in &doc.controls {
        match ctrl.kind {
            ControlKind::TextBox | ControlKind::DropDown => {
                out.push_str(&format!(
                    "    pub {}: String,\n",
                    rust_field_name(&ctrl.name)
                ));
            }
            ControlKind::Slider => {
                out.push_str(&format!(
                    "    pub {}: i32,\n",
                    rust_field_name(&ctrl.name)
                ));
            }
            ControlKind::RadioBox => {
                out.push_str(&format!(
                    "    pub {}_checked: bool,\n",
                    rust_field_name(&ctrl.name)
                ));
            }
            ControlKind::Timer => {
                out.push_str(&format!(
                    "    pub {}_ticks: u64,\n",
                    rust_field_name(&ctrl.name)
                ));
            }
            ControlKind::Button | ControlKind::Label | ControlKind::PictureBox => {}
        }
    }
    out.push_str("}\n\n");

    out.push_str("impl Default for DesignedApp {\n");
    out.push_str("    fn default() -> Self {\n        Self {\n");
    out.push_str(&format!("            form_opacity: {opacity:.3},\n"));
    for ctrl in &doc.controls {
        match ctrl.kind {
            ControlKind::TextBox | ControlKind::DropDown => {
                out.push_str(&format!(
                    "            {}: {:?}.to_owned(),\n",
                    rust_field_name(&ctrl.name),
                    ctrl.text
                ));
            }
            ControlKind::Slider => {
                out.push_str(&format!(
                    "            {}: {},\n",
                    rust_field_name(&ctrl.name),
                    ctrl.value
                ));
            }
            ControlKind::RadioBox => {
                out.push_str(&format!(
                    "            {}_checked: {},\n",
                    rust_field_name(&ctrl.name),
                    ctrl.checked
                ));
            }
            ControlKind::Timer => {
                out.push_str(&format!(
                    "            {}_ticks: 0,\n",
                    rust_field_name(&ctrl.name)
                ));
            }
            ControlKind::Button | ControlKind::Label | ControlKind::PictureBox => {}
        }
    }
    out.push_str("        }\n    }\n}\n\n");

    out.push_str("impl eframe::App for DesignedApp {\n");
    out.push_str(&format!(
        "    fn clear_color(&self, _visuals: &egui::Visuals) -> [f32; 4] {{\n        let _ = self.form_opacity;\n        {clear}\n    }}\n\n"
    ));

    out.push_str("    fn update(&mut self, ctx: &egui::Context, _frame: &mut eframe::Frame) {\n");
    out.push_str(&format!(
        "        // Theme: {} | client_area_only={}\n",
        doc.theme.as_str(),
        doc.client_area_only
    ));
    out.push_str(&format!(
        "        // Form \"{title}\" — {}×{}  font={} {}pt  border={:?}  start={:?}\n",
        doc.width,
        doc.height,
        escape_rust_string(&doc.font_name),
        doc.font_size,
        doc.border_style,
        doc.start_position
    ));
    {
        let pal = doc.theme.palette();
        out.push_str(&format!(
            "        let mut style = (*ctx.style()).clone();\n        style.override_font_id = Some(egui::FontId::proportional({:.1}));\n        style.spacing.button_padding = egui::vec2({:.1}, {:.1});\n        style.spacing.item_spacing = egui::vec2({:.1}, {:.1});\n        style.animation_time = {:.2};\n        style.visuals.widgets.inactive.corner_radius = egui::CornerRadius::same({});\n        style.visuals.widgets.hovered.corner_radius = egui::CornerRadius::same({});\n        style.visuals.widgets.active.corner_radius = egui::CornerRadius::same({});\n        ctx.set_style(style);\n",
            doc.font_size.clamp(6.0, 72.0),
            pal.button_pad_x, pal.button_pad_y, pal.item_spacing, pal.item_spacing,
            pal.animation_secs, pal.button_radius, pal.button_radius, pal.button_radius,
        ));
    }
    out.push_str("        egui::CentralPanel::default()\n");
    out.push_str("            .frame(egui::Frame::none().fill(");
    out.push_str(&back);
    out.push_str("))\n");
    out.push_str("            .show(ctx, |ui| {\n");
    out.push_str(&format!(
        "                ui.set_min_size(egui::vec2({:.1}, {:.1}));\n",
        doc.width as f32, doc.height as f32
    ));
    out.push_str("                let origin = ui.min_rect().min;\n\n");

    for ctrl in &doc.controls {
        out.push_str(&emit_control_ui(ctrl, opacity, doc.theme.palette().button_radius, doc.theme.palette().bold_buttons, doc.theme.palette().uppercase_buttons));
        out.push('\n');
    }

    out.push_str("            });\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

fn emit_control_ui(ctrl: &Control, form_opacity: f32, button_radius: u8, bold_buttons: bool, uppercase_buttons: bool) -> String {
    let x = ctrl.rect.x as f32;
    let y = ctrl.rect.y as f32;
    let w = ctrl.rect.width as f32;
    let h = ctrl.rect.height as f32;
    let field = rust_field_name(&ctrl.name);
    let text = escape_rust_string(&ctrl.text);
    let font_size = ctrl.font_size.clamp(6.0, 72.0);
    let font_family = font_family_expr(&ctrl.font_name);
    let fore = color_expr_with_opacity(ctrl.fore_color, form_opacity);
    let back = color_expr_with_opacity(ctrl.back_color, form_opacity);
    let enabled = ctrl.enabled;

    if ctrl.kind == ControlKind::Timer {
        let interval = ctrl.interval_ms.max(1);
        if enabled {
            return format!(
                "                // {} (Timer) interval={}ms enabled=true\n                {{\n                    ctx.request_repaint_after(std::time::Duration::from_millis({interval}));\n                    self.{field}_ticks += 1;\n                    // TODO: handle {field} tick (tick count: self.{field}_ticks)\n                }}\n",
                ctrl.name, interval
            );
        }
        return format!(
            "                // {} (Timer) interval={}ms enabled=false\n                // Timer disabled: no ticks.\n",
            ctrl.name, interval
        );
    }

    let mut body = String::new();
    body.push_str(&format!(
        "                        ui.style_mut().override_font_id = Some(egui::FontId::new({font_size:.1}, {font_family}));\n"
    ));

    match ctrl.kind {
        ControlKind::Button => {
            let shown = if uppercase_buttons { text.to_uppercase() } else { text.clone() };
            let shown = escape_rust_string(&shown);
            let strong = if bold_buttons { ".strong()" } else { "" };
            body.push_str(&format!(
                "                        let btn = egui::Button::new(egui::RichText::new(\"{shown}\"){strong}.color({fore})).fill({back}).corner_radius(egui::CornerRadius::same({}));\n",
                button_radius
            ));
            body.push_str(&format!(
                "                        if ui.add_enabled({enabled}, btn).clicked() {{\n                            // Handle {field} click\n                        }}\n"
            ));
        }
        ControlKind::TextBox => {
            let mut edit = if ctrl.multiline {
                format!("egui::TextEdit::multiline(&mut self.{field})")
            } else {
                format!("egui::TextEdit::singleline(&mut self.{field})")
            };
            edit.push_str(&format!(".text_color({fore})"));
            if ctrl.password_char.is_some() {
                edit.push_str(".password(true)");
            }
            if ctrl.read_only {
                edit.push_str(".interactive(false)");
            }
            body.push_str(&format!(
                "                        ui.add_enabled_ui({enabled}, |ui| {{\n                            ui.add_sized(ui.available_size(), {edit});\n                        }});\n"
            ));
        }
        ControlKind::Label => {
            body.push_str(&format!(
                "                        ui.add_enabled({enabled}, egui::Label::new(egui::RichText::new(\"{text}\").color({fore})));\n"
            ));
        }
        ControlKind::Slider => {
            let orient = match ctrl.orientation {
                Orientation::Horizontal => "",
                Orientation::Vertical => ".vertical()",
            };
            body.push_str(&format!(
                "                        ui.add_enabled_ui({enabled}, |ui| {{\n                            ui.add(egui::Slider::new(&mut self.{field}, {}..={}){orient});\n                        }});\n",
                ctrl.minimum, ctrl.maximum
            ));
        }
        ControlKind::DropDown => {
            body.push_str(&format!(
                "                        ui.add_enabled_ui({enabled}, |ui| {{\n                            egui::ComboBox::from_id_source(\"{field}\")\n                                .selected_text(self.{field}.clone())\n                                .width(ui.available_width())\n                                .show_ui(ui, |ui| {{\n                                    ui.selectable_value(&mut self.{field}, \"{text}\".to_owned(), \"{text}\");\n                                    ui.selectable_value(&mut self.{field}, \"Option 2\".to_owned(), \"Option 2\");\n                                }});\n                        }});\n"
            ));
        }
        ControlKind::RadioBox => {
            body.push_str(&format!(
                "                        ui.add_enabled_ui({enabled}, |ui| {{\n                            ui.checkbox(&mut self.{field}_checked, egui::RichText::new(\"{text}\").color({fore}));\n                        }});\n"
            ));
        }
        ControlKind::PictureBox => {
            let img = escape_rust_string(&ctrl.image_path);
            body.push_str(&format!(
                "                        // PictureBox image: \"{img}\" (add an image loader such as egui_extras to display it)\n                        egui::Frame::none().fill({back}).stroke(egui::Stroke::new(1.0, {fore})).show(ui, |ui| {{\n                            ui.centered_and_justified(|ui| {{\n                                ui.add_enabled({enabled}, egui::Label::new(egui::RichText::new(\"🖼 {img}\").color({fore})));\n                            }});\n                        }});\n"
            ));
        }
        ControlKind::Timer => unreachable!("timer handled above"),
    }

    format!(
        r#"                // {} ({:?}) @ ({}, {}) {}×{} enabled={} font={} {font_size}pt
                {{
                    let rect = egui::Rect::from_min_size(
                        origin + egui::vec2({x:.1}, {y:.1}),
                        egui::vec2({w:.1}, {h:.1}),
                    );
                    ui.allocate_ui_at_rect(rect, |ui| {{
{body}                    }});
                }}
"#,
        ctrl.name,
        ctrl.kind,
        ctrl.rect.x,
        ctrl.rect.y,
        ctrl.rect.width,
        ctrl.rect.height,
        ctrl.enabled,
        escape_rust_string(&ctrl.font_name),
    )
}

fn font_family_expr(font_name: &str) -> &'static str {
    let lower = font_name.to_ascii_lowercase();
    if lower.contains("mono") || lower.contains("consolas") || lower.contains("courier") {
        "egui::FontFamily::Monospace"
    } else {
        "egui::FontFamily::Proportional"
    }
}

fn color_expr_with_opacity(c: RgbaColor, opacity: f32) -> String {
    let a = ((c.a as f32) * opacity.clamp(0.0, 1.0)).round() as u8;
    format!(
        "egui::Color32::from_rgba_unmultiplied({}, {}, {}, {a})",
        c.r, c.g, c.b
    )
}

fn clear_color_array(c: RgbaColor, opacity: f32) -> String {
    let a = (c.a as f32 / 255.0) * opacity.clamp(0.0, 1.0);
    format!(
        "[{:.4}, {:.4}, {:.4}, {:.4}]",
        c.r as f32 / 255.0,
        c.g as f32 / 255.0,
        c.b as f32 / 255.0,
        a
    )
}

pub fn rust_field_name(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_alphanumeric() {
            if c.is_ascii_uppercase() && i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else if c == '_' {
            out.push('_');
        }
    }
    if out.is_empty() {
        "control".to_owned()
    } else if out.chars().next().unwrap().is_ascii_digit() {
        format!("c_{out}")
    } else {
        out
    }
}

fn escape_rust_string(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Combined preview used by the Code tab when no file is selected.
pub fn generate_preview(doc: &FormDocument) -> String {
    let mut out = String::new();
    out.push_str("========== src/main.rs ==========\n");
    out.push_str(&generate_main_rs(doc));
    out.push_str("\n========== src/app.rs ==========\n");
    out.push_str(&generate_app_rs(doc));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{ControlKind, FormDocument};

    #[test]
    fn generates_picturebox_and_timer() {
        let mut doc = FormDocument::new_blank();
        doc.add_control(ControlKind::PictureBox, 10.0, 10.0);
        doc.selected_control_mut().unwrap().image_path = "assets/cat.png".to_owned();
        doc.add_control(ControlKind::Timer, 200.0, 10.0);
        doc.selected_control_mut().unwrap().interval_ms = 250;

        let app = generate_app_rs(&doc);
        assert!(app.contains("assets/cat.png"), "picturebox path in generated code");
        assert!(app.contains("timer1_ticks: u64"), "timer tick counter field");
        assert!(app.contains("request_repaint_after(std::time::Duration::from_millis(250))"));
    }
}

#[cfg(test)]
mod theme_tests {
    use super::*;
    use crate::model::{ControlKind, FormDocument, FormTheme};

    #[test]
    fn generated_code_reflects_theme_and_client_area_only() {
        let mut doc = FormDocument::new_blank();
        doc.add_control(ControlKind::Button, 10.0, 10.0);
        doc.apply_theme(FormTheme::Fun);
        doc.client_area_only = true;

        let main = generate_main_rs(&doc);
        assert!(main.contains(".with_decorations(false)"), "client-area-only in main.rs");

        let app = generate_app_rs(&doc);
        assert!(app.contains("// Theme: Fun"), "theme name in app.rs");
        assert!(app.contains("corner_radius(egui::CornerRadius::same(24))"), "Fun button radius");
        // Fun button color from the palette is baked into the button fill.
        assert!(app.contains("150, 80, 220"), "Fun button color in app.rs");
        // Shape / spacing / motion / font style from the palette.
        assert!(app.contains("style.spacing.button_padding = egui::vec2(16.0, 8.0)"));
        assert!(app.contains("style.animation_time = 0.35"));
        assert!(app.contains(".strong()"), "Fun buttons are bold");
    }
}
